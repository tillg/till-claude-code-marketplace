// Bundle src/ into dist/md2html.mjs with base.css and the version inlined.
import fs from 'node:fs';
import * as esbuild from 'esbuild';

const here = new URL('..', import.meta.url);
const inlineAssets = {
  name: 'inline-assets',
  setup(b) {
    b.onResolve({ filter: /\/assets\.mjs$/ }, (args) => ({ path: args.path, namespace: 'assets' }));
    b.onLoad({ filter: /.*/, namespace: 'assets' }, () => {
      const css = fs.readFileSync(new URL('src/base.css', here), 'utf8');
      const { version } = JSON.parse(fs.readFileSync(new URL('package.json', here), 'utf8'));
      return { contents: `export const baseCss = ${JSON.stringify(css)};\nexport const version = ${JSON.stringify(version)};\n`, loader: 'js' };
    });
  },
};

/** Build the bundle and return its text (without writing when `write` is false). */
export async function bundle({ write = true } = {}) {
  const result = await esbuild.build({
    absWorkingDir: new URL('.', here).pathname, entryPoints: ['src/index.mjs'],
    bundle: true, platform: 'node', format: 'esm', target: 'node20',
    write: false, legalComments: 'none', charset: 'utf8',
    banner: { js: "// md2html: generated by `npm run bundle` from src/. Do not edit.\nimport { createRequire as __md2htmlRequire } from 'node:module';\nconst require = __md2htmlRequire(import.meta.url);" },
    plugins: [inlineAssets],
  });
  const text = result.outputFiles[0].text;
  if (write) { fs.mkdirSync(new URL('dist/', here), { recursive: true }); fs.writeFileSync(new URL('dist/md2html.mjs', here), text); }
  return text;
}

if (process.argv[1] && new URL(import.meta.url).pathname === fs.realpathSync(process.argv[1])) {
  await bundle();
  console.log('wrote dist/md2html.mjs');
}
