// The cheat sheet, generated from the registry: Markdown for people and skills, JSON for editor menus.
import { directives, PREFIX } from './registry.mjs';

const plainSnippet = (s) => s.replace(/\$\{\d+\|([^,|]*)[^}]*\}/g, '$1').replace(/\$\{\d+:?([^}]*)\}/g, '$1');

function attrText(d) {
  const entries = Object.entries(d.attrs);
  if (!entries.length) return 'none';
  return entries.map(([k, s]) => `\`${k}\` (${s.required ? 'required' : 'optional'}${s.enum ? `: ${s.enum.map((v) => `\`${v}\``).join(' · ')}` : ', text'})`).join(', ');
}

export function syntaxJson() {
  return directives.map((d) => ({
    name: d.name, form: d.form, syntax: `${d.name === 'cards' ? '::::' : PREFIX[d.form]}${d.name}`,
    attrs: d.attrs, children: d.children, ...(d.parent ? { parent: d.parent } : {}),
    summary: d.summary, menu: d.menu,
  }));
}

export function syntaxMarkdown() {
  const out = [
    '# md2html syntax',
    '',
    '<!-- Generated by `md2html syntax` from src/registry.mjs. Do not edit. -->',
    '',
    'A report is GitHub-flavoured Markdown plus frontmatter and the directives below. Everything',
    'else (section numbers, ids, TOC, table frames, figures, menu bar) is derived by the build.',
    '',
    '## Frontmatter',
    '',
    '```yaml',
    '---',
    'title: "Browser-only: can we drop the server?"   # required',
    'created: 2026-09-27                              # required, ISO date',
    'edited: 2026-09-28                               # required, ISO date, >= created; set by hand',
    'status: research                                 # required: research | ongoing | implemented',
    'subtitle: "Report for [spec #03](spec.md)."      # optional, inline Markdown; quote it if it has " #" or ": "',
    'description: One sentence for search engines.   # optional, defaults to the subtitle',
    '---',
    '```',
    '',
    'No other keys are allowed.',
    '',
    '## Directives',
    '',
    '| Directive | Form | Attributes | What it is |',
    '|---|---|---|---|',
    ...directives.map((d) => `| \`${d.name === 'cards' ? '::::' : PREFIX[d.form]}${d.name}\` | ${d.form} | ${attrText(d)} | ${d.summary} |`),
    '',
  ];
  for (const d of directives) {
    out.push(`### ${d.menu.label}`, '', '```markdown', plainSnippet(d.menu.snippet), '```', '');
  }
  out.push(
    '## Derived layout (no syntax needed)',
    '',
    '- `## Heading` sections are numbered automatically. Do not type the numbers.',
    '- `## Heading {#id}` sets a stable anchor; otherwise the id is a slug of the text.',
    '- A table of contents appears once there are 4 or more `##` sections.',
    '- Every table gets a scrolling frame.',
    '- An image alone in a paragraph becomes a figure; its alt text is the caption. A `.mmd` file',
    '  next to an `.svg` is linked as the diagram source. Mermaid is not rendered by the build.',
    '- Links to other reports may point at the `.md`; the build rewrites them to `.html`.',
    '- Raw HTML is not rendered. Unknown directives render as literal text and fail `lint`.',
    '',
  );
  return out.join('\n');
}
