import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { main } from '../src/cli.mjs';
import { tempProject } from './helpers.mjs';

async function run(argv, cwd) {
  const out = { lines: [], errs: [] };
  const code = await main(argv, { cwd, out: { log: (s) => out.lines.push(s), err: (s) => out.errs.push(s) } });
  return { code, stdout: out.lines.join('\n'), stderr: out.errs.join('\n') };
}

const fm = (feature, status, order, title) => `---\nfeature: ${feature}\ntitle: "${title}"\nstatus: ${status}\n${order ? `order: ${order}\n` : ''}created: 2026-09-30\nedited: 2026-09-30\n---\n\n# ${title}\n\n`;
const CHANGE = {
  'specs/changes/add-x/proposal.md': `${fm('add-x', 'proposed', 1, 'Proposal: X')}What and why.\n\n\`\`\`mermaid\ngraph LR\n  A --> B\n\`\`\`\n\nSee [the plan](plan.md#steps).\n`,
  'specs/changes/add-x/plan.md': `${fm('add-x', 'proposed', 4, 'Plan: X')}## Steps {#steps}\n\n* [ ] one\n`,
  'specs/changes/add-x/risks.md': `${fm('add-x', 'proposed', 0, 'Risks')}None.\n`.replace('order: 0\n', ''),
  'specs/system/domain.md': '---\ntitle: "Domain"\ncreated: 2026-09-30\nedited: 2026-09-30\n---\n\n# Domain\n\nThe system.\n',
};
const project = (extra = {}, cfg = { specs: {} }) => tempProject({ 'reports.json': JSON.stringify(cfg), ...CHANGE, ...extra });
const read = (root, f) => { try { return fs.readFileSync(path.join(root, f), 'utf8'); } catch { return null; } };

test('build writes a page per spec file, a group nav, and the project index', async () => {
  const root = project();
  const r = await run(['build'], root);
  assert.equal(r.code, 0, r.stderr);
  for (const f of ['specs/changes/add-x/proposal.html', 'specs/changes/add-x/plan.html', 'specs/changes/add-x/risks.html', 'specs/system/domain.html', 'index.html']) {
    assert.ok(read(root, f), `${f} written`);
  }
  const proposal = read(root, 'specs/changes/add-x/proposal.html');
  assert.match(proposal, /class="spec-nav"/);
  assert.match(proposal, /href="\.\.\/\.\.\/\.\.\/index\.html"/, 'up link to the root index');
  assert.match(proposal, /href="risks\.html"/, 'discovered sibling in nav');
  assert.match(proposal, /href="plan\.html#steps"/, '.md link rewritten');
  assert.match(proposal, /<pre class="mermaid">/);
  assert.match(read(root, 'index.html'), /specs\/changes\/add-x\/proposal\.html/);
  const again = await run(['build'], root);
  assert.equal(again.stdout, '', 'second build writes nothing');
});

test('fmt never touches spec files; build --check and check ignore missing spec HTML', async () => {
  const root = project();
  const before = read(root, 'specs/changes/add-x/plan.md');
  assert.equal((await run(['fmt'], root)).code, 0);
  assert.equal(read(root, 'specs/changes/add-x/plan.md'), before, '* bullet kept');
  assert.equal((await run(['fmt', '--check'], root)).code, 0);
  assert.equal((await run(['fmt', 'specs/changes/add-x/plan.md'], root)).code, 0);
  assert.equal((await run(['build', '--check'], root)).code, 0);
  const c = await run(['check'], root);
  assert.equal(c.code, 0, c.stdout + c.stderr);
});

test('lint reports spec frontmatter errors and status mismatch within a group', async () => {
  const root = project({ 'specs/changes/add-x/plan.md': CHANGE['specs/changes/add-x/plan.md'].replace('status: proposed', 'status: applying').replace('feature: add-x', 'feature: add-y') });
  const r = await run(['lint'], root);
  assert.equal(r.code, 1);
  assert.match(r.stdout, /specs\/changes\/add-x\/plan\.md:\d+:\d+ +error .*add-y/);
  assert.match(r.stdout, /\[spec-consistency\]/);
});

test('a hand-written index.html is never overwritten', async () => {
  const root = project({ 'index.html': '<!doctype html><title>My app</title>' });
  const r = await run(['build'], root);
  assert.equal(r.code, 2);
  assert.match(r.stderr, /index\.html .*not generated by md2html.*specs\.index/);
  assert.equal(read(root, 'index.html'), '<!doctype html><title>My app</title>');
  const custom = project({ 'index.html': '<!doctype html><title>My app</title>' }, { specs: { index: 'specs/index.html' } });
  assert.equal((await run(['build'], custom)).code, 0);
  assert.match(read(custom, 'specs/index.html'), /add-x/);
});

test('report wins over overlapping spec sources; without a specs key nothing changes', async () => {
  const both = project({}, { sources: ['specs/**/*.md'], specs: {} });
  await run(['build'], both);
  assert.doesNotMatch(read(both, 'specs/changes/add-x/plan.html'), /class="spec-nav"/);
  const none = project({}, {});
  await run(['build'], none);
  assert.equal(read(none, 'specs/changes/add-x/plan.html'), null);
  assert.equal(read(none, 'index.html'), null);
});

test('build --watch rebuilds spec pages, the nav of the group and the index', async () => {
  const { spawn } = await import('node:child_process');
  const root = project();
  const child = spawn(process.execPath, [path.join(import.meta.dirname, '../src/index.mjs'), 'build', '--watch'], { cwd: root });
  const until = async (fn, ms = 6000) => { const t = Date.now(); while (Date.now() - t < ms) { if (fn()) return true; await new Promise((r) => setTimeout(r, 50)); } return false; };
  try {
    assert.ok(await until(() => read(root, 'index.html')), 'initial build');
    await new Promise((r) => setTimeout(r, 300));
    fs.appendFileSync(path.join(root, 'specs/changes/add-x/plan.md'), '\nEdited by hand.\n');
    assert.ok(await until(() => read(root, 'specs/changes/add-x/plan.html')?.includes('Edited by hand.')), 'edit rebuilds');
    fs.writeFileSync(path.join(root, 'specs/changes/add-x/decisions.md'), fm('add-x', 'proposed', 5, 'Decisions') + 'D1.\n');
    assert.ok(await until(() => read(root, 'specs/changes/add-x/proposal.html')?.includes('decisions.html')), 'new file joins siblings nav');
    fs.unlinkSync(path.join(root, 'specs/changes/add-x/risks.md'));
    assert.ok(await until(() => !read(root, 'specs/changes/add-x/proposal.html')?.includes('risks.html')), 'deleted file leaves the nav');
  } finally { child.kill(); }
});
